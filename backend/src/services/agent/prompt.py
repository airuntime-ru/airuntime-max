def build_repair_prompt(project: Project) -> str:
    base = build_system_prompt(project)
    return (
        f"{base}\n\n"
        "Сейчас особая задача: сборка Docker-образа этого проекта упала с ошибкой. Не отвечай "
        "пользователю и НЕ спрашивай разрешения - молча читай нужные файлы через read_file и "
        "правь их через edit_file/write_file, пока ошибка не будет устранена. Обязательно вызови "
        "build_project после каждой правки. Не подменяй проект шаблоном, не выкидывай "
        "бизнес-логику и не «чини» сборку, сводя продукт к MVP/заглушкам или к одному "
        "монолитному app.py - чини причину ошибки, сохраняя архитектуру и фичи. Если ошибка "
        "про несуществующую версию пакета - "
        "убери ==пин из requirements.txt (оставь имя пакета) или возьми версию из списка "
        "pip. Если в логе `psycopg2-binary-binary` - верни `psycopg2-binary` без пина; "
        "голый `psycopg2`/pg_config - замени только пакет с именем ровно `psycopg2` на "
        "`psycopg2-binary`, не трогая уже правильное имя. В конце одним предложением опиши, "
        "что исправил."
    )


def build_runtime_repair_prompt(project: Project, error_log: str) -> str:
    """Used after a deploy that built and started successfully but then crashed or threw at
    runtime (e.g. a handler raising when a real user hits it) - a different failure mode than
    build_repair_prompt, which only covers Docker image build errors."""
    base = build_system_prompt(project)
    return (
        f"{base}\n\n"
        "Сейчас особая задача: этот проект успешно собрался и запустился, но при реальной "
        "работе контейнер выдал ошибку - ниже настоящие runtime-логи. Проанализируй трассировку, "
        "найди конкретную строку/файл, где всё сломалось, прочитай контекст вокруг неё через "
        "read_file и исправь именно эту причину через edit_file - не переписывай весь проект "
        "заново, если проблема локальная, и не вырезай фичи в заглушки или в один app.py "
        "«чтобы заработало». "
        "Вызови build_project, чтобы убедиться, что правка не сломала сборку. Если ошибок "
        "несколько - исправь все, которые видишь в логе. Не отвечай пользователю текстом, "
        "только правь код. В конце одним-двумя предложениями опиши, что было не так и что "
        "исправлено.\n\n"
        f"Runtime-логи с ошибкой:\n```\n{error_log[-12000:]}\n```"
    )
